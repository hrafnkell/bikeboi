export const circuitGroups = CIRCUIT_GROUPS.map((g) => ({ ...g, circuits: circuits.filter((c) => c.group === g.id) }));

export function findCircuit(id: string): Circuit {
  return circuits.find((c) => c.id === id) ?? circuits[0];
}
